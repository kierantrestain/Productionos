/** Acceptance 6, 8, 23, 24, 25 — Airtable import lineage, reconciliation, idempotency, attachments. Synthetic fixture only. */
import { cpSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { and, eq, inArray, sql } from "drizzle-orm";
import { closeDb, db } from "@/db";
import * as s from "@/db/schema";
import { runImport, LEGACY_PRODUCTION_TITLE } from "@/server/import/runner";
import { DISPOSITION } from "@/server/import/disposition";
import { SPECS } from "@/server/import/specs";
import { makeOrg } from "../support/factory";

const FIXTURE = path.resolve(__dirname, "../fixtures/airtable-synthetic");
let orgId: string;

const OPERATIONAL = { episodes: s.episodes, scenes: s.scenes, shots: s.shots, shoot_days: s.shootDays, people: s.people, engagements: s.engagements, resources: s.resources, locations: s.locations, post_tasks: s.postTasks, schedule_blocks: s.scheduleBlocks, scene_people: s.scenePeople, scene_resources: s.sceneResources, release_forms: s.releaseForms, ip_projects: s.ipProjects, workflow_definitions: s.workflowDefinitions, approval_requests: s.approvalRequests, attachments: s.attachments, productions: s.productions } as const;
async function counts() {
  const out: Record<string, number> = {};
  for (const [k, t] of Object.entries(OPERATIONAL)) out[k] = Number((await db.select({ n: sql<number>`count(*)::int` }).from(t as any).where(eq((t as any).orgId, orgId)))[0].n);
  return out;
}

beforeAll(async () => { orgId = (await makeOrg("Import")).id; });
afterAll(async () => { await closeDb(); });

describe("disposition register", () => {
  it("covers all 90 audited tables exactly once, and every spec has a disposition", () => {
    expect(DISPOSITION).toHaveLength(90);
    expect(new Set(DISPOSITION.map((d) => d.tableId)).size).toBe(90);
    expect(DISPOSITION.filter((d) => d.base === "Ovation OS")).toHaveLength(68);
    expect(DISPOSITION.reduce((a, d) => a + d.auditRecords, 0)).toBe(796);
    for (const spec of SPECS) expect(DISPOSITION.some((d) => d.table === spec.table), spec.table).toBe(true);
  });
});

describe("Airtable import (synthetic export)", () => {
  it("dry run computes a report but writes nothing", async () => {
    const before = await counts();
    const r = await runImport({ orgId, exportDir: FIXTURE, mode: "dry_run" });
    expect(r.totals.imported).toBeGreaterThan(0);
    expect(await counts()).toEqual(before);
    expect((await db.select().from(s.sourceRecords).where(eq(s.sourceRecords.orgId, orgId))).length).toBe(0);
    expect((await db.select().from(s.importBatches).where(eq(s.importBatches.orgId, orgId))).length).toBe(0);
  });

  it("applies with lineage, correct counts and links", async () => {
    const before = await counts();
    const r = await runImport({ orgId, exportDir: FIXTURE, mode: "apply" });
    const after = await counts();
    const delta = (k: string) => after[k] - before[k];
    expect(delta("productions")).toBe(1);
    const [legacy] = await db.select().from(s.productions).where(and(eq(s.productions.orgId, orgId), eq(s.productions.isLegacyImport, true)));
    expect(legacy.title).toBe(LEGACY_PRODUCTION_TITLE);
    expect(delta("episodes")).toBe(1);
    expect(delta("scenes")).toBe(3);
    expect(delta("shots")).toBe(2);
    expect(delta("shoot_days")).toBe(2); // two days on the same date are both kept
    expect(delta("people")).toBe(2);
    expect(delta("engagements")).toBe(2);
    expect(delta("resources")).toBe(2);
    expect(delta("scene_people")).toBe(3);
    expect(delta("scene_resources")).toBe(2);
    expect(delta("schedule_blocks")).toBe(3);
    expect(delta("ip_projects")).toBe(2);
    expect(delta("approval_requests")).toBe(1);
    expect(delta("workflow_definitions")).toBe(1);

    const [ep] = await db.select().from(s.episodes).where(eq(s.episodes.productionId, legacy.id));
    expect(ep.synopsisOriginal).toBe(ep.synopsis);
    const imported = await db.select().from(s.shots).where(eq(s.shots.productionId, legacy.id));
    expect(imported.every((x) => !x.autoGenerated && x.generationKey === null)).toBe(true);

    // Every source record has lineage with hash + batch.
    const lineage = await db.select().from(s.sourceRecords).where(eq(s.sourceRecords.orgId, orgId));
    expect(lineage).toHaveLength(r.totals.sourceCount);
    expect(lineage.every((l) => l.sourceHash.length === 64 && l.importBatchId === r.batchId)).toBe(true);
    expect(lineage.find((l) => l.recordId === "recSynRl1")?.migrationStatus).toBe("archived");
    expect(JSON.stringify(lineage.map((l) => l.raw))).not.toMatch(/example\.invalid/); // signed URLs scrubbed

    // Ovation specs imported as blocked drafts, approvals as historical.
    const [wf] = await db.select().from(s.workflowDefinitions).where(and(eq(s.workflowDefinitions.orgId, orgId), eq(s.workflowDefinitions.key, "AUTO-901")));
    expect([wf.status, wf.disposition, wf.source, wf.sourceDeployment]).toEqual(["draft", "blocked", "ovation_spec", "spec_only"]);
    const [ap] = await db.select().from(s.approvalRequests).where(eq(s.approvalRequests.orgId, orgId));
    expect(ap.historical).toBe(true);
    expect(ap.decidedBy).toBeNull();

    // Orphan link + unmapped field + signed-without-evidence flagged.
    const ex = await db.select().from(s.importExceptions).where(eq(s.importExceptions.importBatchId, r.batchId));
    expect(ex.some((e) => e.kind === "orphan_link" && e.detail.includes("recSynGhost"))).toBe(true);
    expect(ex.some((e) => e.kind === "unmapped_field" && e.detail.includes("Shoe Size"))).toBe(true);
    expect(ex.filter((e) => e.kind === "unmapped_field" && e.detail.includes("Shoe Size"))).toHaveLength(1);
    expect(ex.some((e) => e.kind === "validation" && e.recordId === "recSynCa2")).toBe(true);
    expect(r.inventory.expectedTables).toBe(90);
    expect(r.inventory.missingTables.length).toBeGreaterThan(70); // the fixture is a subset: drift is reported, not hidden
  });

  it("reconciles Editing against Scenes without creating scenes (acceptance 6)", async () => {
    const [legacy] = await db.select().from(s.productions).where(and(eq(s.productions.orgId, orgId), eq(s.productions.isLegacyImport, true)));
    const scenes = await db.select().from(s.scenes).where(eq(s.scenes.productionId, legacy.id));
    expect(scenes).toHaveLength(3);
    const edits = await db.select().from(s.postTasks).where(and(eq(s.postTasks.productionId, legacy.id), eq(s.postTasks.kind, "edit")));
    expect(edits).toHaveLength(4);
    expect(edits.filter((e) => e.sceneId)).toHaveLength(3);
    const lineage = await db.select().from(s.sourceRecords).where(and(eq(s.sourceRecords.orgId, orgId), inArray(s.sourceRecords.recordId, ["recSynEd1", "recSynEd4"])));
    expect(lineage.every((l) => l.targetEntityType === "post_tasks")).toBe(true);
    const ex = await db.select().from(s.importExceptions).where(and(eq(s.importExceptions.orgId, orgId), eq(s.importExceptions.kind, "reconciliation"), eq(s.importExceptions.recordId, "recSynEd4")));
    expect(ex.length).toBeGreaterThanOrEqual(1);
  });

  it("stores verified attachments and rejects bad hashes / undownloaded files (acceptance 25)", async () => {
    const atts = await db.select().from(s.attachments).where(eq(s.attachments.orgId, orgId));
    expect(atts).toHaveLength(1);
    expect(atts[0].filename).toBe("synthetic-headshot.txt");
    expect(atts[0].sha256).toBe(JSON.parse(readFileSync(path.join(FIXTURE, "export_manifest.json"), "utf8")).attachment_manifest[0].sha256);
    expect(atts[0].sourceAttachmentId).toBe("attSynGood");
    const ex = await db.select().from(s.importExceptions).where(and(eq(s.importExceptions.orgId, orgId), eq(s.importExceptions.kind, "attachment_failed")));
    expect(ex.some((e) => e.detail.includes("SHA-256 mismatch"))).toBe(true);
    expect(ex.some((e) => e.detail.includes("not downloaded"))).toBe(true);
  });

  it("creates no notifications or actionable events (imports are side-effect free)", async () => {
    const ev = await db.select().from(s.outboxEvents).where(eq(s.outboxEvents.orgId, orgId));
    expect(ev.filter((e) => e.status === "pending")).toHaveLength(0);
    expect(ev.every((e) => e.origin === "import" && e.status === "suppressed")).toBe(true);
    expect(ev.some((e) => e.type === "scene.ready_for_shots")).toBe(false);
    expect((await db.select().from(s.outboundMessages).where(eq(s.outboundMessages.orgId, orgId)))).toHaveLength(0);
  });

  it("second run is idempotent: no new operational rows, everything unchanged (acceptance 24)", async () => {
    const before = await counts();
    const r = await runImport({ orgId, exportDir: FIXTURE, mode: "apply" });
    expect(await counts()).toEqual(before);
    expect(r.totals.imported).toBe(0);
    expect(r.totals.updated).toBe(0);
    expect(r.totals.unchanged).toBe(r.totals.sourceCount - r.totals.archived - r.totals.exceptions);
    expect(r.attachments.alreadyStored).toBe(1);
  });

  it("a changed source cell updates the existing target instead of duplicating it", async () => {
    const dir = mkdtempSync(path.join(tmpdir(), "pos-import-"));
    cpSync(FIXTURE, dir, { recursive: true });
    const file = path.join(dir, "Sappening_Production/records/tblW1sDnBQzmdFpBP.json");
    const data = JSON.parse(readFileSync(file, "utf8"));
    data.records[2].fields.fldSc2 = "Synthetic Scene Three (revised)";
    writeFileSync(file, JSON.stringify(data));
    const before = await counts();
    const r = await runImport({ orgId, exportDir: dir, mode: "apply" });
    expect(await counts()).toEqual(before);
    expect(r.totals.updated).toBe(1);
    const [lin] = await db.select().from(s.sourceRecords).where(and(eq(s.sourceRecords.orgId, orgId), eq(s.sourceRecords.recordId, "recSynSc3")));
    expect(lin.migrationStatus).toBe("updated");
    const [scene] = await db.select().from(s.scenes).where(eq(s.scenes.id, lin.targetId!));
    expect(scene.title).toBe("Synthetic Scene Three (revised)");
  });
});
